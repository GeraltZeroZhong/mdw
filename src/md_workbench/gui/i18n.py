def tr(key: str, lang: str = "en_US", default: str | None = None) -> str:
    text = UI_TEXT.get(key)
    if text is None:
        text = default if default is not None else humanize_key(key)
    return safe_text(text)


def field_label(field_name: str, lang: str = "en_US") -> str:
    text = FIELD_LABELS.get(field_name)
    if text is None:
        text = humanize_key(field_name)
    return safe_text(text)


def section_label(section_key: str, lang: str = "en_US") -> str:
    text = SECTION_LABELS.get(section_key)
    if text is None:
        text = humanize_key(section_key)
    return safe_text(text)


def section_hint(section_key: str, lang: str = "en_US") -> str:
    hint_key = SECTION_HINT_KEYS.get(section_key)
    return tr(hint_key, lang, default="") if hint_key else ""
